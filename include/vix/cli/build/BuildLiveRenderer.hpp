#pragma once

#include <cstddef>
#include <iosfwd>
#include <string>

#include <vix/cli/build/BuildEvent.hpp>

namespace vix::cli::build
{
  /**
   * @brief Renders semantic build events as human-friendly terminal output.
   *
   * BuildLiveRenderer is responsible only for presentation. It does not
   * parse CMake or Ninja output and it does not execute build processes.
   *
   * It receives BuildEvent objects generated by the live build pipeline
   * and converts them into concise messages intended to be understandable
   * by both experienced and beginner C++ developers.
   *
   * When the destination stream is an interactive terminal, transient
   * build stages such as configuration, compilation, and linking are
   * rendered on a reusable terminal line. Progress updates therefore
   * replace the previous status instead of filling the terminal with one
   * line per compiled source file.
   *
   * Example interactive output:
   *
   * @code
   *   ✓ Project ready  orelunza
   *   ✓ Build configured
   *   → Compiling  18 / 48  src/game/World.cpp
   * @endcode
   *
   * The compilation line can then be replaced in-place by:
   *
   * @code
   *   → Compiling  19 / 48  src/game/Player.cpp
   * @endcode
   *
   * When the output stream is not attached to an interactive terminal,
   * terminal control sequences are disabled automatically and ordinary
   * newline-delimited output is produced instead. This keeps redirected
   * logs and CI output readable.
   */
  class BuildLiveRenderer
  {
  public:
    /**
     * @brief Construct a build renderer.
     *
     * Terminal capability is detected from the supplied output stream.
     * std::cout and std::cerr can be recognized as terminal-backed streams
     * when their corresponding file descriptors are attached to a TTY.
     *
     * Other streams, such as std::ostringstream or redirected output, are
     * treated as non-interactive.
     *
     * @param output Destination stream for user-facing build messages.
     */
    explicit BuildLiveRenderer(
        std::ostream &output);

    /**
     * @brief Render one semantic build event.
     *
     * The event is routed to the renderer dedicated to its build stage.
     * The output stream is flushed after rendering so live progress is
     * visible immediately.
     *
     * @param event Build event to render.
     */
    void render(
        const BuildEvent &event);

    /**
     * @brief Reset all renderer state.
     *
     * Any active transient terminal line is finalized before state is
     * cleared. The renderer can then be reused for another independent
     * build.
     */
    void reset() noexcept;

    /**
     * @brief Return whether interactive terminal rendering is active.
     *
     * @return true when in-place terminal updates are enabled.
     */
    [[nodiscard]]
    bool interactive() const noexcept;

  private:
    /**
     * @brief Render project loading/preparation events.
     *
     * @param event Project-related event.
     */
    void render_project_event(
        const BuildEvent &event);

    /**
     * @brief Render CMake configuration events.
     *
     * @param event Configuration-related event.
     */
    void render_configure_event(
        const BuildEvent &event);

    /**
     * @brief Render dependency resolution events.
     *
     * @param event Dependency-related event.
     */
    void render_dependency_event(
        const BuildEvent &event);

    /**
     * @brief Render compilation events and source-file progress.
     *
     * CompileProgress events use the reusable live terminal line whenever
     * interactive output is available.
     *
     * @param event Compilation-related event.
     */
    void render_compile_event(
        const BuildEvent &event);

    /**
     * @brief Render linker events.
     *
     * @param event Link-related event.
     */
    void render_link_event(
        const BuildEvent &event);

    /**
     * @brief Render the final build result.
     *
     * @param event BuildSucceeded or BuildFailed event.
     */
    void render_result_event(
        const BuildEvent &event);

    /**
     * @brief Format numeric build progress.
     *
     * A total value of zero represents unknown total work and produces an
     * empty string.
     *
     * @param current Current build operation index.
     * @param total Total number of known build operations.
     * @return Human-readable progress such as "18 / 48".
     */
    [[nodiscard]]
    std::string progress_text(
        std::size_t current,
        std::size_t total) const;

    /**
     * @brief Write or replace the current transient terminal line.
     *
     * In interactive mode the previous live line is cleared and replaced.
     * In non-interactive mode the supplied text is emitted as a regular
     * newline-delimited log line.
     *
     * @param text Complete visible text for the status line.
     */
    void write_live_line(
        const std::string &text);

    /**
     * @brief Replace an active live line with a permanent completed line.
     *
     * In interactive mode the transient line is cleared before the final
     * line is printed. In non-interactive mode this simply prints a normal
     * line.
     *
     * @param text Completed status line.
     */
    void finish_live_line(
        const std::string &text);

    /**
     * @brief Finalize the current transient line without replacing it.
     *
     * Does nothing when no live line is active.
     */
    void end_live_line();

    /**
     * @brief Clear the currently displayed interactive terminal line.
     *
     * This function emits terminal control sequences only when interactive
     * rendering is enabled.
     */
    void clear_live_line();

    /**
     * @brief Detect whether the configured stream is attached to a TTY.
     *
     * @return true when in-place terminal rendering can safely be used.
     */
    [[nodiscard]]
    bool detect_interactive_output() const noexcept;

    /**
     * @brief Destination for all rendered build messages.
     */
    std::ostream &output_;

    /**
     * @brief Whether terminal in-place updates are enabled.
     */
    bool interactive_{false};

    /**
     * @brief Whether a transient terminal line is currently displayed.
     */
    bool liveLineActive_{false};

    /**
     * @brief Whether project loading has already been shown.
     */
    bool projectShown_{false};

    /**
     * @brief Whether configuration start has already been shown.
     */
    bool configureShown_{false};

    /**
     * @brief Whether dependency resolution start has already been shown.
     */
    bool dependenciesShown_{false};

    /**
     * @brief Whether compilation start has already been shown.
     */
    bool compileShown_{false};

    /**
     * @brief Whether linking start has already been shown.
     */
    bool linkShown_{false};
  };

} // namespace vix::cli::build
